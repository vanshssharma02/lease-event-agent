"""Notification dispatch module for lease-event-agent.

Dispatches notifications for routed memos via SMTP or local logging, with strict suppression
when low-confidence flags are active. Writes a tamper-evident NOTIFY audit entry for all events.
"""

import email
import json
import logging
import smtplib
import uuid
from datetime import datetime, timezone
from email.mime.multipart import MIMEMultipart
from email.mime.text import MIMEText
from pathlib import Path
from typing import Optional, Dict, Any, Union

from app.config import settings
from app.db import get_connection
from app.audit import append_entry, hash_payload
from app.schemas import LeaseEventMemo
from app.retrieval import RetrievedLeaseContext

logger = logging.getLogger(__name__)


def send_notification(
    run_id: str,
    lease_id: str,
    memo: LeaseEventMemo,
    context: RetrievedLeaseContext,
    no_auto_notify: bool = False,
    db_path: Optional[Union[str, Path]] = None,
) -> Dict[str, Any]:
    """Notify the relevant asset manager when a memo is routed to the inbox.

    If no_auto_notify is True (e.g. low confidence), dispatch is suppressed and logged.
    Always appends a cryptographic NOTIFY entry to the audit log.
    """
    notif_id = str(uuid.uuid4())
    now_iso = datetime.now(timezone.utc).isoformat()
    recipient = context.lease.asset_manager
    asset_name = context.lease.asset_name

    # 1. Check if auto-notification is suppressed (Low Confidence)
    if no_auto_notify or memo.confidence_score < 0.6:
        detail = {
            "status": "SKIPPED_LOW_CONFIDENCE",
            "reason": f"Confidence score {memo.confidence_score:.2f} is below threshold 0.60. Auto-notification suppressed.",
            "recipient": recipient,
        }
        append_entry(
            event_type="NOTIFY",
            run_id=run_id,
            input_hash=hash_payload(memo.model_dump()),
            output_hash=hash_payload(detail),
            detail=detail,
            db_path=db_path,
        )
        return {
            "notif_id": notif_id,
            "dispatched": False,
            "status": "SKIPPED_LOW_CONFIDENCE",
            "recipient": recipient,
        }

    # 2. Prepare notification content
    subject = (
        f"[ACTION REQUIRED] Upcoming {memo.event_type.value} Notice: "
        f"{memo.tenant_name.value} at {asset_name} ({memo.days_to_event} Days)"
    )

    body_lines = [
        f"ATTENTION: {recipient}",
        "",
        f"A commercial lease lifecycle event requires human review and sign-off in the Approvals Inbox.",
        "",
        f"Asset: {asset_name} ({context.lease.asset_id})",
        f"Tenant: {memo.tenant_name.value}",
        f"Event Type: {memo.event_type.value}",
        f"Event Date: {memo.event_date.date} ({memo.days_to_event} days remaining)",
        f"Passing Rent at Risk: {memo.passing_rent.currency} {memo.passing_rent.amount:,.2f}",
        f"Urgency: {memo.urgency.value}",
        f"Confidence Score: {memo.confidence_score:.2f}",
        "",
        "EXECUTIVE SUMMARY:",
        memo.executive_summary,
        "",
        "RECOMMENDED ACTIONS:",
    ]
    for act in memo.recommended_actions:
        body_lines.append(f" - {act}")

    body_lines.extend([
        "",
        f"Review & Approve via Inbox: {settings.API_URL}/inbox/{run_id}",
        "Generated by lease-event-agent (Synthetic Asset Register)",
    ])
    body_text = "\n".join(body_lines)

    # 3. Dispatch via SMTP or Local Log
    channel = "LOCAL"
    status = "SENT"

    if settings.SMTP_HOST and settings.SMTP_USER and settings.SMTP_FROM:
        channel = "SMTP"
        try:
            msg = MIMEMultipart()
            msg["From"] = settings.SMTP_FROM
            msg["To"] = f"{recipient.lower().replace(' ', '.')}@example.com"
            msg["Subject"] = subject
            msg.attach(MIMEText(body_text, "plain"))

            with smtplib.SMTP(settings.SMTP_HOST, settings.SMTP_PORT or 587, timeout=10) as server:
                if settings.SMTP_PASSWORD:
                    server.starttls()
                    server.login(settings.SMTP_USER, settings.SMTP_PASSWORD)
                server.send_message(msg)
            logger.info(f"Notification email dispatched via SMTP to {msg['To']}")
        except Exception as e:
            logger.warning(f"SMTP dispatch failed: {e}. Falling back to local logging.")
            channel = "LOCAL_FALLBACK"

    # Persist to local notifications table and file log
    conn = get_connection(db_path)
    try:
        with conn:
            conn.execute(
                """
                INSERT INTO notifications (notif_id, run_id, lease_id, recipient, subject, body, channel, status, created_at)
                VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?);
                """,
                (notif_id, run_id, lease_id, recipient, subject, body_text, channel, status, now_iso),
            )
    finally:
        conn.close()

    # Append to log file
    try:
        settings.NOTIFICATIONS_LOG_PATH.parent.mkdir(parents=True, exist_ok=True)
        with open(settings.NOTIFICATIONS_LOG_PATH, "a", encoding="utf-8") as f:
            f.write(f"\n[{now_iso}] [{channel}] To: {recipient} | Subject: {subject}\n{body_text}\n" + ("=" * 70) + "\n")
    except Exception as e:
        logger.warning(f"Failed to write to notification log file: {e}")

    # 4. Append NOTIFY audit entry
    notif_detail = {
        "notif_id": notif_id,
        "recipient": recipient,
        "channel": channel,
        "status": status,
        "subject": subject,
    }
    append_entry(
        event_type="NOTIFY",
        run_id=run_id,
        input_hash=hash_payload(memo.model_dump()),
        output_hash=hash_payload(notif_detail),
        detail=notif_detail,
        db_path=db_path,
    )

    return {
        "notif_id": notif_id,
        "dispatched": True,
        "status": status,
        "recipient": recipient,
        "channel": channel,
    }
